"""
親密氛圍描述生成器

根據「關係階段 + 互動意願」生成一句人類可讀的氛圍描述。
這個描述不需要存資料，每次刷新重新計算即可。

V1 映射表（戀人階段）：
- 低：有點忍耐
- 中：有點害羞
- 高：特別黏人

V2 可擴展：
- 加入身體狀態的影響（例如熱度高 + 意願低 = 「忍著不說」）
- 加入時間因素（例如深夜 + 意願高 = 「想要抱著睡」）
"""

# 氛圍映射表（關係階段 → 互動意願 → 描述）
ATMOSPHERE_MAP = {
    "陌生": {
        "低": "保持距離",
        "中": "禮貌客氣",
        "高": "友善好奇"
    },
    "熟悉": {
        "低": "有點累了",
        "中": "慢慢靠近",
        "高": "樂意聊天"
    },
    "親近": {
        "低": "需要空間",
        "中": "有點依偎",
        "高": "想撒嬌"
    },
    "戀人": {
        "低": "有點忍耐",
        "中": "有點害羞",
        "高": "特別黏人"
    }
}


def generate_atmosphere(relationship_stage: str, willingness: str) -> str:
    """
    生成親密氛圍描述。
    
    Args:
        relationship_stage: 關係階段（陌生/熟悉/親近/戀人）
        willingness: 互動意願（低/中/高）
    
    Returns:
        氛圍描述字串（例如：「特別黏人」）
    """
    return ATMOSPHERE_MAP.get(relationship_stage, {}).get(willingness, "平靜相處")
